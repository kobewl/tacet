//! # Tacet 桌面壳
//!
//! 这一层把六个核心 crate 组装成一个能跑的应用，并且**只做三件事**：
//!
//! 1. **持有真值**（[`state::AppState`]）—— 工作状态机、上下文引擎、
//!    需求评分、决策引擎、数据库都在这里，用一把锁串起来
//! 2. **驱动时间**（[`scheduler`]）—— 每 10 秒 tick 一次，把时间推给状态机
//! 3. **响应界面**（[`commands`]）—— 把用户的点击翻译成领域操作
//!
//! ## 一条必须守住的边界
//!
//! 这一层**不含任何业务规则**。如果你在这里看到「如果连续工作超过 50 分钟
//! 就提醒」这样的判断，那说明它写错了位置 —— 那条规则属于
//! `tacet-health`（算需求）或 `tacet-core::policy`（做决策）。
//!
//! 壳层代码应该薄到「读一遍就能确认它没做坏事」。这样业务逻辑才能被
//! 单元测试覆盖，而不是被困在需要真实窗口才能跑的集成测试里。
//!
//! ## 两处例外
//!
//! [`logging`] 与 [`windows`] 不属于上述三条，但它们**只能待在这里**：
//! 前者要写文件（核心层不该有副作用），后者要碰窗口系统（属于平台细节）。
//! 它们共同的特点是「只做一件事、没有业务判断」，所以不违反上面那条边界。

pub mod commands;
pub mod logging;
pub mod scheduler;
pub mod state;
pub mod windows;

pub use state::AppState;
