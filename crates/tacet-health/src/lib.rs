//! # tacet-health —— 健康需求引擎
//!
//! 这个 crate 只回答一个问题：**「现在，我有多需要休息 / 喝水 / 活动 / 护眼？」**
//!
//! 答案不是「要 / 不要」，而是四个 0.0~1.0 的连续分数。为什么坚持用连续值：
//!
//! - **0.58 和 0.95 是完全不同的处境**。前者可以再等等，后者该说话了。
//!   二值的「到点了」会把这个差别抹平，让提醒变成机械的闹钟 ——
//!   而那正是番茄钟被嫌弃的原因（README 里那句「只认识时钟，不认识你」）。
//! - 连续值可以**融合**。两类需求都在涨的时候，谁更急一目了然，
//!   这为 v0.2 的 Reminder Fusion 铺好了路。
//! - 连续值可以**被学习**。v0.3 的用户模型要调整的是参数，不是开关。
//!
//! ## 计算方式：距离上次满足的时长 ÷ 用户设定的间隔
//!
//! ```text
//!   需求强度 = clamp(距上次满足的时间 / 提醒间隔, 0.0, 1.0)
//! ```
//!
//! 也就是说：**刚喝完水 = 0.0，到了设定的间隔 = 1.0**。
//! 直觉、可解释、可测试，而且用户改设置时能立刻理解影响 ——
//! 把饮水间隔从 45 分钟调到 60 分钟，就是「同样时长下分数变低」。
//!
//! ## v0.1 的诚实声明
//!
//! 这个模型是**产品上合理的起点，不是医学模型**。真实的人体节律、个体差异、
//! 活动强度都没有被建模。v0.3 会引入按时间的衰减曲线与个体参数。
//! 在那之前，宁可公式朴素但可解释，也不要一个看起来精密却没人说得清的黑箱。

