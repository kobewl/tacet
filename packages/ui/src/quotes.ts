/**
 * 上一次抽中的下标。
 *
 * 存在模块里而不是组件里，是因为它的作用域应该是「应用进程」：
 * 用户连续休息两次，第二次不该又看到同一句。
 */
let lastIndex = -1;

/**
 * 随机取一句，且不会和上一次重复。
 *
 * 不重复这一点很重要：池子只有几十条，随机就可能连着抽中同一条。
 * 而「重复」恰恰会让用户意识到「这是个固定的池子」—— 一旦意识到，
 * 句子的温度就没了。所以宁可多写三行代码，把这种小概率的失望堵掉。
 */
export function pickQuote(): string {
  if (QUOTES.length === 0) {
    return "";
  }

  let index = Math.floor(Math.random() * QUOTES.length);
  if (index === lastIndex) {
    // 撞上了就顺延一位 —— 仍然是随机的，只是排除了「和上次一样」
    index = (index + 1) % QUOTES.length;
  }
  lastIndex = index;

  // 索引是自己算出来的，一定落在范围内（TS 的 noUncheckedIndexedAccess
  // 看不到这一点，所以这里显式兜一下底）。
  return QUOTES[index] ?? "";
}
